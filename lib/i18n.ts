export function money(n: number, lang: Lang): string {
  return lang === "he" ? `₪${n}` : `${n} NIS`;
}

// Picks a localized field off a row shaped like { xxxHe, xxxEn, xxxFr },
// falling back to Hebrew when a translation is missing (admin-added content).
export function pickField<T extends object>(row: T, base: string, lang: Lang): string {
  const suffix = lang === "he" ? "He" : lang === "en" ? "En" : "Fr";
  const rec = row as Record<string, unknown>;
  const val = rec[`${base}${suffix}`];
  if (typeof val === "string" && val.trim()) return val;
  const fallback = rec[`${base}He`];
  return typeof fallback === "string" ? fallback : "";
}
